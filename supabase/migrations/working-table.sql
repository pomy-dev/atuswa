do $$
declare t text;
begin
  foreach t in array array[
  'affiliates', 'affiliate_leadership', 'affiliate_status_history', 'affiliate_documents',
  'members', 'affiliate_payments', 'affiliate_notifications', 'affiliate_links', 'affiliate_status_requests',
  'member_transfer_requests', 'financial_records', 'projects', 'project_phases', 'project_team_members',
  'project_resources', 'project_files', 'events', 'event_files', 'event_invitations', 'helpdesk_cases',
  'helpdesk_handlers', 'helpdesk_notes', 'helpdesk_documents',
] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "Authenticated users can manage %s" on public.%I', t, t);
    execute format('create policy "Internal users can manage %s" on public.%I for all to authenticated using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.affiliate_id is null and p.role in (''sg'',''branch_admin'',''treasurer'',''project_coordinator'',''events_manager''))) with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.affiliate_id is null and p.role in (''sg'',''branch_admin'',''treasurer'',''project_coordinator'',''events_manager'')))', t, t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
  end loop;
end $$;

