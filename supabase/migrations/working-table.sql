--Domain schema for app modules.Auth, profiles, roles, board users and activity
--logs are managed by existing migrations and are intentionally excluded.
create extension if not exists pgcrypto;


create table if not exists public.affiliates(
  id text primary key default gen_random_uuid():: text,
  affiliate_id text not null unique,
  official_name text not null,
  acronym text not null,
  registration_number text,
  affiliation_date date not null,
  founding_date date,
  physical_address text not null default '', postal_address text,
  phone_numbers text[] not null default '{}', email text, website text, social_media text,
  correspondence_contact jsonb not null default '{}':: jsonb,
  last_congress_date date, constitution_version text,
  executive_committee_size integer not null default 0,
  declared_membership integer not null default 0, paid_up_membership integer not null default 0,
  gender_breakdown jsonb not null default '{"female":0,"male":0,"other":0}':: jsonb,
  age_groups text, sectors text[] not null default '{}', regions text[] not null default '{}',
  shop_stewards integer not null default 0, dues_rate text, payment_history text,
  financial_standing text not null default 'Good standing'
    check(financial_standing in ('Good standing', 'Arrears', 'Suspended')),
  bank_details text,
  status text not null default 'Provisional'
    check(status in ('Active', 'Provisional', 'Suspended', 'Expelled', 'Withdrawn')),
  notes text, active boolean not null default true,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create table if not exists public.affiliate_leadership(
  id bigint generated by default as identity primary key,
  affiliate_id text not null references public.affiliates(id) on delete cascade,
  position text not null, name text not null, email text, phone text, term_of_office text
);
create table if not exists public.affiliate_status_history(
  id bigint generated by default as identity primary key,
  affiliate_id text not null references public.affiliates(id) on delete cascade,
  status text not null check(status in ('Active', 'Provisional', 'Suspended', 'Expelled', 'Withdrawn')),
  reason text not null default '', changed_at timestamptz not null default now(), changed_by text
);
create table if not exists public.affiliate_documents(
  id text primary key default gen_random_uuid():: text,
  affiliate_id text not null references public.affiliates(id) on delete cascade,
  name text not null,
  category text not null default 'Other' check(category in ('Constitution', 'Registration', 'Minutes', 'Resolution', 'Financial', 'Other')),
  version text, url text, uploaded_at timestamptz not null default now(),
  archived_at timestamptz, archived_by text
);

create table if not exists public.members(
  id text primary key default gen_random_uuid():: text,
  branch_id text references public.branches(id) on delete set null,
  affiliate_id text references public.affiliates(id) on delete set null,
  name text not null, email text not null default '', member_id text not null unique,
  phone text not null default '', address text not null default '', date_of_birth date,
  workplace text not null default '', next_of_kin text not null default '', next_of_kin_phone text not null default '',
  gender text not null default 'Other' check(gender in ('Male', 'Female', 'Other')),
  job_category text,
  subscription_status text check(subscription_status in ('Paid', 'Pending', 'In arrears')),
  tucoswa_status text check(tucoswa_status in ('Active', 'Resigned', 'Deceased', 'Transferred')),
  photo_url text, join_date date not null default current_date,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.affiliate_payments(
  id text primary key default gen_random_uuid():: text,
  affiliate_id text not null references public.affiliates(id) on delete cascade,
  amount numeric(14, 2) not null check(amount >= 0), payment_date date, reference text, notes text,
  recorded_by text, recorded_at timestamptz not null default now()
);
create table if not exists public.affiliate_notifications(
  id text primary key default gen_random_uuid():: text,
  affiliate_id text not null references public.affiliates(id) on delete cascade,
  subject text, message text not null default '', status text not null default 'Queued',
  queued_at timestamptz not null default now(), queued_by text
);
create table if not exists public.affiliate_links(
  id text primary key default gen_random_uuid():: text,
  affiliate_id text not null references public.affiliates(id) on delete cascade,
  link_type text not null, target_id text not null, relation text not null default '',
  linked_at timestamptz not null default now(), linked_by text
);
create table if not exists public.affiliate_status_requests(
  id text primary key default gen_random_uuid():: text,
  affiliate_id text not null references public.affiliates(id) on delete cascade,
  requested_status text not null check(requested_status in ('Active', 'Provisional', 'Suspended', 'Expelled', 'Withdrawn')),
  reason text not null default '', status text not null default 'Pending', requested_by text,
  requested_at timestamptz not null default now(), reviewed_by text, reviewed_at timestamptz
);
create table if not exists public.member_transfer_requests(
  id text primary key default gen_random_uuid():: text,
  member_id text not null references public.members(id) on delete cascade,
  from_branch_id text references public.branches(id) on delete set null,
  to_branch_id text references public.branches(id) on delete set null,
  from_affiliate_id text references public.affiliates(id) on delete set null,
  to_affiliate_id text references public.affiliates(id) on delete set null,
  reason text not null default '', status text not null default 'Pending', requested_by text,
  requested_at timestamptz not null default now(), reviewed_by text, reviewed_at timestamptz
);

create table if not exists public.projects(
  id text primary key default gen_random_uuid():: text,
  branch_id text references public.branches(id) on delete set null,
  affiliate_id text references public.affiliates(id) on delete set null,
  title text not null, description text not null default '', coordinator text not null default '',
  status text not null default 'planning' check(status in ('starting', 'in_progress', 'finished', 'planning', 'ongoing', 'completed')),
  budget numeric(14, 2) not null default 0 check(budget >= 0), timeline text not null default '',
  start_date date, end_date date, created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.project_phases(
  id text primary key default gen_random_uuid():: text,
  project_id text not null references public.projects(id) on delete cascade,
  name text not null, description text not null default '', start_date date, end_date date,
  status text not null default 'planning' check(status in ('starting', 'in_progress', 'finished', 'planning', 'ongoing', 'completed'))
);
create table if not exists public.project_team_members(
  id text primary key default gen_random_uuid():: text,
  project_id text not null references public.projects(id) on delete cascade,
  user_id uuid references public.profiles(id) on delete set null, role text not null default '', assigned_date date not null default current_date
);
create table if not exists public.project_resources(
  id text primary key default gen_random_uuid():: text,
  project_id text not null references public.projects(id) on delete cascade,
  name text not null, quantity numeric(12, 2) not null default 0, unit text not null default '',
  cost numeric(14, 2) not null default 0 check(cost >= 0), used_date date
);
create table if not exists public.project_files(
  id text primary key default gen_random_uuid():: text,
  project_id text not null references public.projects(id) on delete cascade,
  file_kind text not null check(file_kind in ('image', 'document')), name text not null,
  url text not null, size_bytes bigint not null default 0 check(size_bytes >= 0), uploaded_at timestamptz not null default now()
);

create index if not exists members_branch_idx on public.members(branch_id);
create index if not exists members_affiliate_idx on public.members(affiliate_id);
create index if not exists projects_branch_idx on public.projects(branch_id);